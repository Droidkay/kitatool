import SwiftUI
import AppKit
import CryptoKit

/// Watches the clipboard, keeps the history, and saves it to disk.
@MainActor
final class ClipStore: ObservableObject {
    @Published private(set) var clips: [Clip] = []
    @Published var query = "" { didSet { resetSelection() } }
    @Published var filter: ClipFilter = .all { didSet { resetSelection() } }
    @Published var selectedID: UUID?
    @Published var focusToken = 0

    @Published var paused = false
    @Published var maxItems: Int { didSet { defaults.set(maxItems, forKey: "maxItems"); prune(); save() } }
    @Published var expiryDays: Int { didSet { defaults.set(expiryDays, forKey: "expiryDays"); prune(); save() } }
    @Published var pasteDirectly: Bool { didSet { defaults.set(pasteDirectly, forKey: "pasteDirectly") } }
    @Published var captureImages: Bool { didSet { defaults.set(captureImages, forKey: "captureImages") } }
    @Published var captureFiles: Bool { didSet { defaults.set(captureFiles, forKey: "captureFiles") } }
    @Published var ignoredBundles: [String] { didSet { defaults.set(ignoredBundles, forKey: "ignoredBundles") } }

    private let defaults = UserDefaults.standard
    private var lastChange = NSPasteboard.general.changeCount
    private var timer: Timer?
    private var pauseTask: Task<Void, Never>?

    /// Password managers and similar apps: never saved.
    static let alwaysIgnored: Set<String> = [
        "com.agilebits.onepassword7", "com.1password.1password", "com.agilebits.onepassword-osx",
        "com.bitwarden.desktop", "com.apple.keychainaccess", "com.apple.Passwords",
        "com.lastpass.LastPass", "com.dashlane.dashlanephonefinal", "in.sinew.Enpass-Desktop",
        "com.keepassxc.keepassxc", "com.nordpass.macos.NordPass"
    ]

    private static let skipTypes: [NSPasteboard.PasteboardType] = [
        .init("org.nspasteboard.ConcealedType"), .init("org.nspasteboard.TransientType"),
        .init("org.nspasteboard.AutoGeneratedType"), .init("com.agilebits.onepassword"),
        .init("de.petermaurer.TransientPasteboardType")
    ]

    // MARK: storage locations

    static let folder: URL = {
        let base = FileManager.default.urls(for: .applicationSupportDirectory, in: .userDomainMask)[0]
        let dir = base.appendingPathComponent("KitaClips", isDirectory: true)
        try? FileManager.default.createDirectory(at: dir.appendingPathComponent("images"), withIntermediateDirectories: true)
        return dir
    }()
    private var historyURL: URL { ClipStore.folder.appendingPathComponent("history.json") }
    private var legacyURL: URL { ClipStore.folder.appendingPathComponent("clips.json") }
    static func imageURL(_ name: String) -> URL { folder.appendingPathComponent("images").appendingPathComponent(name) }

    init() {
        let d = UserDefaults.standard
        maxItems = d.object(forKey: "maxItems") as? Int ?? 200
        expiryDays = d.object(forKey: "expiryDays") as? Int ?? 30
        pasteDirectly = d.object(forKey: "pasteDirectly") as? Bool ?? false
        captureImages = d.object(forKey: "captureImages") as? Bool ?? true
        captureFiles = d.object(forKey: "captureFiles") as? Bool ?? true
        ignoredBundles = d.stringArray(forKey: "ignoredBundles") ?? []
        load()
        prune()
    }

    func start() {
        lastChange = NSPasteboard.general.changeCount
        let t = Timer(timeInterval: 0.4, repeats: true) { [weak self] _ in
            let me = self
            Task { @MainActor in me?.poll() }
        }
        RunLoop.main.add(t, forMode: .common)
        timer = t
    }

    // MARK: list shown in the panel

    var visible: [Clip] {
        let q = query.trimmingCharacters(in: .whitespaces).lowercased()
        return clips
            .filter { filter.matches($0) }
            .filter { q.isEmpty || $0.searchText.lowercased().contains(q) || ($0.sourceApp?.lowercased().contains(q) ?? false) }
            .sorted { a, b in
                if a.pinned != b.pinned { return a.pinned }
                return a.lastUsed > b.lastUsed
            }
    }

    var count: Int { clips.count }

    func resetSelection() {
        selectedID = visible.first?.id
    }

    func moveSelection(_ delta: Int) {
        let list = visible
        guard !list.isEmpty else { selectedID = nil; return }
        let i = list.firstIndex { $0.id == selectedID } ?? -1
        let n = max(0, min(list.count - 1, i + delta))
        selectedID = list[n].id
    }

    var selected: Clip? {
        guard let id = selectedID else { return nil }
        return clips.first { $0.id == id }
    }

    // MARK: watching the clipboard

    private func poll() {
        let pb = NSPasteboard.general
        guard pb.changeCount != lastChange else { return }
        lastChange = pb.changeCount
        guard !paused else { return }
        let types = pb.types ?? []
        if types.contains(where: { ClipStore.skipTypes.contains($0) }) { return }

        let front = NSWorkspace.shared.frontmostApplication
        let bundle = front?.bundleIdentifier ?? ""
        if ClipStore.alwaysIgnored.contains(bundle) || ignoredBundles.contains(bundle) { return }
        let appName = front?.localizedName

        if captureFiles,
           let urls = pb.readObjects(forClasses: [NSURL.self], options: [.urlReadingFileURLsOnly: true]) as? [URL],
           !urls.isEmpty {
            var c = Clip(kind: .file)
            c.filePaths = urls.map { $0.path }
            c.sourceApp = appName
            c.sourceBundle = bundle
            add(c)
            return
        }

        if let s = pb.string(forType: .string), !s.trimmingCharacters(in: .whitespacesAndNewlines).isEmpty {
            guard s.count <= 200_000 else { return }
            var c = Clip(kind: ClipKind.detect(s))
            c.text = s
            c.sourceApp = appName
            c.sourceBundle = bundle
            add(c)
            return
        }

        if captureImages, pb.availableType(from: [.png, .tiff]) != nil {
            let png: Data?
            if let d = pb.data(forType: .png) {
                png = d
            } else if let tiff = pb.data(forType: .tiff), let rep = NSBitmapImageRep(data: tiff) {
                png = rep.representation(using: .png, properties: [:])
            } else {
                png = nil
            }
            guard let data = png, data.count < 30_000_000 else { return }
            let hash = SHA256.hash(data: data).map { String(format: "%02x", $0) }.joined()
            if let i = clips.firstIndex(where: { $0.contentHash == hash }) {
                clips[i].lastUsed = Date()
                save()
                return
            }
            let name = UUID().uuidString + ".png"
            do { try data.write(to: ClipStore.imageURL(name)) } catch { return }
            var c = Clip(kind: .image)
            c.imageFile = name
            c.contentHash = hash
            if let rep = NSBitmapImageRep(data: data) {
                c.imageWidth = rep.pixelsWide
                c.imageHeight = rep.pixelsHigh
            }
            c.sourceApp = appName
            c.sourceBundle = bundle
            add(c)
        }
    }

    private func add(_ new: Clip) {
        if let i = clips.firstIndex(where: { same($0, new) }) {
            clips[i].lastUsed = Date()
            clips[i].sourceApp = new.sourceApp ?? clips[i].sourceApp
            clips[i].sourceBundle = new.sourceBundle ?? clips[i].sourceBundle
        } else {
            clips.insert(new, at: 0)
        }
        prune()
        save()
    }

    private func same(_ a: Clip, _ b: Clip) -> Bool {
        if a.kind == .file || b.kind == .file { return a.filePaths == b.filePaths && a.filePaths != nil }
        if let x = a.text, let y = b.text { return x == y }
        return false
    }

    // MARK: actions

    /// Puts a clip back on the clipboard.
    func copyToPasteboard(_ clip: Clip, overrideText: String? = nil) {
        let pb = NSPasteboard.general
        pb.clearContents()
        if let t = overrideText {
            pb.setString(t, forType: .string)
        } else {
            switch clip.kind {
            case .image:
                if let f = clip.imageFile, let img = NSImage(contentsOf: ClipStore.imageURL(f)) {
                    pb.writeObjects([img])
                }
            case .file:
                pb.writeObjects(clip.fileURLs as [NSURL])
            default:
                pb.setString(clip.text ?? "", forType: .string)
            }
        }
        lastChange = pb.changeCount
        if let i = clips.firstIndex(where: { $0.id == clip.id }) {
            clips[i].lastUsed = Date()
            clips[i].useCount += 1
        }
        if let t = overrideText, t != clip.text {
            var c = Clip(kind: ClipKind.detect(t))
            c.text = t
            c.sourceApp = "Kita Clips"
            add(c)
        } else {
            save()
        }
    }

    func togglePin(_ clip: Clip) {
        guard let i = clips.firstIndex(where: { $0.id == clip.id }) else { return }
        clips[i].pinned.toggle()
        save()
    }

    func delete(_ clip: Clip) {
        let list = visible
        let idx = list.firstIndex { $0.id == clip.id }
        removeFiles(of: clip)
        clips.removeAll { $0.id == clip.id }
        save()
        if selectedID == clip.id {
            let after = visible
            if let idx, !after.isEmpty { selectedID = after[min(idx, after.count - 1)].id } else { selectedID = after.first?.id }
        }
    }

    func clearUnpinned() {
        for c in clips where !c.pinned { removeFiles(of: c) }
        clips.removeAll { !$0.pinned }
        save()
        resetSelection()
    }

    func ignoreApp(of clip: Clip) {
        guard let b = clip.sourceBundle, !b.isEmpty, !ignoredBundles.contains(b) else { return }
        ignoredBundles.append(b)
    }

    func stopIgnoring(_ bundle: String) {
        ignoredBundles.removeAll { $0 == bundle }
    }

    func setPaused(_ on: Bool, minutes: Int? = nil) {
        pauseTask?.cancel()
        paused = on
        if on, let minutes {
            pauseTask = Task {
                try? await Task.sleep(nanoseconds: UInt64(minutes) * 60_000_000_000)
                if Task.isCancelled { return }
                self.paused = false
            }
        }
    }

    // MARK: housekeeping

    private func prune() {
        let now = Date()
        var removed: [Clip] = []
        if expiryDays > 0 {
            let limit = now.addingTimeInterval(-Double(expiryDays) * 86_400)
            removed += clips.filter { !$0.pinned && $0.lastUsed < limit }
            clips.removeAll { !$0.pinned && $0.lastUsed < limit }
        }
        let unpinned = clips.filter { !$0.pinned }.sorted { $0.lastUsed > $1.lastUsed }
        if unpinned.count > maxItems {
            let drop = Set(unpinned[maxItems...].map { $0.id })
            removed += clips.filter { drop.contains($0.id) }
            clips.removeAll { drop.contains($0.id) }
        }
        for c in removed { removeFiles(of: c) }
    }

    private func removeFiles(of clip: Clip) {
        if let f = clip.imageFile {
            try? FileManager.default.removeItem(at: ClipStore.imageURL(f))
            ThumbCache.shared.remove(f)
        }
    }

    // MARK: saving

    private func load() {
        let fm = FileManager.default
        if let data = try? Data(contentsOf: historyURL) {
            let dec = JSONDecoder()
            dec.dateDecodingStrategy = .iso8601
            if let list = try? dec.decode([Clip].self, from: data) {
                clips = list
                return
            }
            // Damaged file: keep a copy and start fresh instead of failing to open.
            let bad = ClipStore.folder.appendingPathComponent("history-damaged-\(Int(Date().timeIntervalSince1970)).json")
            try? fm.moveItem(at: historyURL, to: bad)
        }
        importLegacy()
    }

    /// Brings over clips from Kita Clips 1.x.
    private func importLegacy() {
        guard let data = try? Data(contentsOf: legacyURL),
              let arr = try? JSONSerialization.jsonObject(with: data) as? [[String: Any]] else { return }
        var out: [Clip] = []
        for d in arr {
            guard let t = d["text"] as? String, !t.isEmpty else { continue }
            var c = Clip(kind: ClipKind.detect(t))
            c.text = t
            c.pinned = d["pinned"] as? Bool ?? false
            c.sourceApp = d["sourceApp"] as? String ?? d["app"] as? String
            out.append(c)
        }
        clips = out
        save()
    }

    private func save() {
        let enc = JSONEncoder()
        enc.dateEncodingStrategy = .iso8601
        guard let data = try? enc.encode(clips) else { return }
        try? data.write(to: historyURL, options: .atomic)
    }
}

/// Small downscaled copies of images for the cards.
final class ThumbCache {
    static let shared = ThumbCache()
    private let cache = NSCache<NSString, NSImage>()

    func image(_ name: String) -> NSImage? {
        if let i = cache.object(forKey: name as NSString) { return i }
        guard let full = NSImage(contentsOf: ClipStore.imageURL(name)) else { return nil }
        let maxSide: CGFloat = 360
        let s = full.size
        let scale = min(1, maxSide / max(s.width, s.height, 1))
        let target = NSSize(width: max(1, s.width * scale), height: max(1, s.height * scale))
        let thumb = NSImage(size: target)
        thumb.lockFocus()
        full.draw(in: NSRect(origin: .zero, size: target), from: .zero, operation: .copy, fraction: 1)
        thumb.unlockFocus()
        cache.setObject(thumb, forKey: name as NSString)
        return thumb
    }

    func remove(_ name: String) { cache.removeObject(forKey: name as NSString) }
}

/// App icons for the "copied from" label.
@MainActor
enum AppIcons {
    private static var cache: [String: NSImage] = [:]
    static func icon(_ bundle: String?) -> NSImage? {
        guard let bundle, !bundle.isEmpty else { return nil }
        if let i = cache[bundle] { return i }
        guard let url = NSWorkspace.shared.urlForApplication(withBundleIdentifier: bundle) else { return nil }
        let i = NSWorkspace.shared.icon(forFile: url.path)
        cache[bundle] = i
        return i
    }
}
